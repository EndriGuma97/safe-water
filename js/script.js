// ==========================================
// LANGUAGE SWITCHING
// ==========================================
function switchLanguage() {
    currentLang = currentLang === 'sq' ? 'en' : 'sq';
    document.documentElement.lang = currentLang;

    // Update language button text
    const langBtn = document.getElementById('langToggle');
    langBtn.querySelector('.lang-text').textContent = currentLang === 'sq' ? 'EN' : 'SQ';

    // Update all translatable elements
    const elements = document.querySelectorAll('[data-translate]');
    elements.forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[currentLang][key]) {
            element.innerHTML = translations[currentLang][key];
        }
    });

    // Update translatable placeholders
    document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
        const key = element.getAttribute('data-translate-placeholder');
        if (translations[currentLang][key]) {
            element.placeholder = translations[currentLang][key];
        }
    });

    // Update translatable aria-labels
    document.querySelectorAll('[data-translate-aria]').forEach(element => {
        const key = element.getAttribute('data-translate-aria');
        if (translations[currentLang][key]) {
            element.setAttribute('aria-label', translations[currentLang][key]);
        }
    });

    // Re-translate a visible form status message
    const formStatus = document.getElementById('formStatus');
    if (formStatus && formStatus.dataset.key && translations[currentLang][formStatus.dataset.key]) {
        formStatus.innerHTML = translations[currentLang][formStatus.dataset.key];
    }

    // Store language preference (storage can be blocked, e.g. private mode)
    try {
        localStorage.setItem('preferredLanguage', currentLang);
    } catch (e) {}
}

// ==========================================
// NAVBAR SCROLL EFFECT
// ==========================================
function handleNavbarScroll() {
    const navbar = document.querySelector('.navbar');
    if (window.scrollY > 50) {
        navbar.classList.add('scrolled');
    } else {
        navbar.classList.remove('scrolled');
    }
}

// ==========================================
// SMOOTH SCROLL
// ==========================================
function smoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                const offsetTop = target.offsetTop - 80;
                window.scrollTo({
                    top: offsetTop,
                    behavior: 'smooth'
                });
            }
        });
    });
}

// ==========================================
// MOBILE MENU TOGGLE
// ==========================================
function setupMobileMenu() {
    const mobileToggle = document.getElementById('mobileToggle');
    const navMenu = document.querySelector('.nav-menu');

    if (mobileToggle) {
        mobileToggle.addEventListener('click', () => {
            navMenu.classList.toggle('active');
            mobileToggle.classList.toggle('active');
        });

        // Close menu when clicking on a link
        const menuLinks = document.querySelectorAll('.nav-menu a');
        menuLinks.forEach(link => {
            link.addEventListener('click', () => {
                navMenu.classList.remove('active');
                mobileToggle.classList.remove('active');
            });
        });
    }
}

// ==========================================
// INTERSECTION OBSERVER FOR ANIMATIONS
// ==========================================
function setupScrollAnimations() {
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -100px 0px'
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.style.opacity = '1';
                entry.target.style.transform = 'translateY(0)';
            }
        });
    }, observerOptions);

    // Observe elements
    const animatedElements = document.querySelectorAll('.phase-card, .benefit-card, .pricing-card, .info-card');
    animatedElements.forEach(el => {
        el.style.opacity = '0';
        el.style.transform = 'translateY(30px)';
        el.style.transition = 'opacity 0.6s ease-out, transform 0.6s ease-out';
        observer.observe(el);
    });
}

// ==========================================
// CTA BUTTON ACTIONS
// ==========================================
function setupCTAButtons() {
    const ctaButtons = document.querySelectorAll('.btn-primary, .btn-secondary, .cta-button');
    ctaButtons.forEach(button => {
        button.addEventListener('click', (e) => {
            // Check if button is inside pricing or hero section
            const isPricingBtn = button.closest('.pricing-card');
            const isHeroBtn = button.closest('.hero');

            if (isPricingBtn || isHeroBtn || button.classList.contains('cta-button')) {
                e.preventDefault();
                // Scroll to contact form
                const contactSection = document.getElementById('contact');
                if (contactSection) {
                    const offsetTop = contactSection.offsetTop - 80;
                    window.scrollTo({
                        top: offsetTop,
                        behavior: 'smooth'
                    });
                }
            }
        });
    });
}

